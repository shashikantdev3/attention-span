"""Write docs/data/offline.js, a copy of all site data as one script.

Browsers block a page opened straight from disk (file://) from fetching JSON. When the
site sees file://, it loads this script instead, so double-clicking docs/index.html works.
GitHub Pages never uses it. run_daily.py and seed/build_seed.py call this automatically.
"""
import json
import sys
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "docs" / "data"
sys.path.insert(0, str(Path(__file__).resolve().parent))


def read(p, default=None):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return default


def bundle():
    index = read(DATA / "editions" / "index.json", {"editions": []})
    months = {}
    for e in index.get("editions", []):
        if e["file"] not in months:
            months[e["file"]] = read(DATA / "editions" / e["file"])
    out = {
        "data/meta.json": read(DATA / "meta.json"),
        "data/timeline.json": read(DATA / "timeline.json", []),
        "data/concepts.json": read(DATA / "concepts.json", []),
        "data/people.json": read(DATA / "people.json", []),
        "data/editions/index.json": index,
        "data/heads.json": read(DATA / "heads.json", {"people": [], "posts": [], "groups": []}),
        **{f"data/editions/{f}": m for f, m in months.items() if m},
    }
    js = "// Generated by tools/bundle_data.py for opening the site from disk. Do not edit.\nwindow.AS_DATA = " + \
         json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (DATA / "offline.js").write_text(js, encoding="utf-8")
    try:  # static pages for search engines and link previews; never blocks the data bundle
        import build_static
        build_static.build()
    except Exception as exc:  # noqa: BLE001
        print(f"static pages skipped: {type(exc).__name__}: {exc}")
    return len(js)


if __name__ == "__main__":
    print(f"wrote docs/data/offline.js ({bundle() // 1024} KB)")
